from datetime import timedelta
from typing import Optional

from fastapi import APIRouter, Depends, HTTPException
from sqlalchemy import func
from sqlalchemy.orm import Session

from app.db.session import get_db
from app.models.database import Alert
from app.core.detection import DETECTION_RULES
from app.core.time import UTC, utc_iso, utc_now


router = APIRouter()


# Map rule IDs to their alert_type for stats lookup
RULE_TO_ALERT_TYPE = {
    "NET-001": "port_scanning",
    "AUTH-001": "ssh_brute_force",
    "AUTH-002": "successful_login_after_failures",
    "HOST-001": "suspicious_command",
}


@router.get("/rules")
async def list_rules(
    enabled_only: bool = False,
    category: Optional[str] = None,
):
    """List all detection rules."""

    rules = DETECTION_RULES

    if enabled_only:
        rules = [
            r for r in rules
            if r.get("enabled", True)
        ]

    if category:
        rules = [
            r for r in rules
            if r.get("category") == category
        ]

    return {
        "total": len(rules),
        "enabled": len([
            r for r in DETECTION_RULES
            if r.get("enabled", True)
        ]),
        "rules": rules,
    }


@router.get("/rules/{rule_id}")
async def get_rule(rule_id: str):
    """Get details of a specific detection rule."""

    rule = next(
        (r for r in DETECTION_RULES if r["id"] == rule_id),
        None,
    )

    if not rule:
        raise HTTPException(
            status_code=404,
            detail="Rule not found",
        )

    return rule


@router.get("/stats")
async def get_detection_stats(
    db: Session = Depends(get_db),
):
    """
    Get detection engine statistics.

    Counts how many times each detection rule has fired
    and returns the most recent trigger time as timezone-aware UTC.
    """

    # ---------------------------------------------------------
    # Count alerts by type
    # ---------------------------------------------------------
    alert_counts = (
        db.query(
            Alert.alert_type,
            func.count(Alert.id).label("count"),
        )
        .group_by(Alert.alert_type)
        .all()
    )

    alert_map = {
        alert_type: count
        for alert_type, count in alert_counts
    }

    # ---------------------------------------------------------
    # Enrich each rule with trigger statistics
    # ---------------------------------------------------------
    rules_with_stats = []

    for rule in DETECTION_RULES:
        alert_type = RULE_TO_ALERT_TYPE.get(
            rule["id"],
            "",
        )

        # Get most recent alert generated by this rule.
        last_alert = None

        if alert_type:
            last_alert = (
                db.query(Alert)
                .filter(
                    Alert.alert_type == alert_type
                )
                .order_by(Alert.created_at.desc())
                .first()
            )

        rules_with_stats.append({
            **rule,

            "trigger_count": alert_map.get(
                alert_type,
                0,
            ),

            # Database stores UTC.
            # API exposes timezone-aware UTC.
            "last_triggered": (
                utc_iso(last_alert.created_at)
                if last_alert
                else None
            ),
        })

    # Sort by trigger count descending
    rules_with_stats.sort(
        key=lambda r: r["trigger_count"],
        reverse=True,
    )

    # ---------------------------------------------------------
    # Summary
    # ---------------------------------------------------------
    total_alerts = sum(alert_map.values())

    return {
        "total_rules": len(DETECTION_RULES),

        "total_alerts_generated": total_alerts,

        "alert_type_distribution": alert_map,

        "rules": rules_with_stats,

        "categories": {
            "network": len([
                r for r in DETECTION_RULES
                if r.get("category") == "network"
            ]),

            "authentication": len([
                r for r in DETECTION_RULES
                if r.get("category") == "authentication"
            ]),

            "host": len([
                r for r in DETECTION_RULES
                if r.get("category") == "host"
            ]),
        },
    }


@router.get("/timeline")
async def get_detection_timeline(
    hours: int = 24,
    db: Session = Depends(get_db),
):
    """
    Get detection activity over time.

    Database timestamps are UTC.
    Timeline buckets are returned as timezone-aware UTC instants.
    """

    # Prevent unreasonable queries
    if hours < 1:
        raise HTTPException(
            status_code=400,
            detail="hours must be greater than 0",
        )

    if hours > 168:
        hours = 168

    # IMPORTANT:
    # Use UTC for database filtering.
    start_time = (
        utc_now()
        - timedelta(hours=hours)
    )

    results = (
        db.query(
            func.strftime(
                "%Y-%m-%dT%H:00:00",
                Alert.created_at,
            ).label("hour"),

            func.count(Alert.id).label("count"),
        )
        .filter(
            Alert.created_at >= start_time
        )
        .group_by("hour")
        .order_by("hour")
        .all()
    )

    timeline = []

    for row in results:
        utc_hour = row[0]

        if utc_hour:
            # SQLite returns the bucket as a string.
            #
            # SQLite's strftime result has no offset, so attach UTC.
            from datetime import datetime

            utc_datetime = datetime.strptime(
                utc_hour,
                "%Y-%m-%dT%H:00:00",
            ).replace(tzinfo=UTC)

            api_hour = utc_iso(utc_datetime)

        else:
            api_hour = None

        timeline.append({
            "hour": api_hour,
            "count": row[1],
        })

    return {
        "hours": hours,
        "timezone": "UTC",
        "display_timezone": "Asia/Kathmandu",
        "timeline": timeline,
    }


@router.get("/coverage")
async def get_detection_coverage(
    db: Session = Depends(get_db),
):
    """Get MITRE ATT&CK coverage summary."""

    # Get all techniques from alerts
    techniques = (
        db.query(
            Alert.mitre_technique,
            func.count(Alert.id).label("count"),
        )
        .filter(
            Alert.mitre_technique.isnot(None)
        )
        .group_by(
            Alert.mitre_technique
        )
        .order_by(
            func.count(Alert.id).desc()
        )
        .all()
    )

    return {
        "total_techniques_covered": len(techniques),

        "techniques": [
            {
                "id": technique_id,
                "alert_count": count,
            }
            for technique_id, count in techniques
        ],
    }
